# ── completeness check: fail loudly if a new route is added to api.py without being added here
# too, instead of silently under-covering it forever ────────────────────────────────────────────

def test_route_inventory_matches_api_py():
    """If this fails, a route was added to (or removed from) api.py without a matching update to
    the AUTHED_ROUTES/OWNER_ROUTES/public-route lists above — go classify it and add it."""
    covered = {p for _, p, _ in AUTHED_ROUTES + OWNER_ROUTES} | {
        "/api/stream", "/api/config", "/healthz", "/auth/name", "/auth/admin", "/auth/test",
        "/auth/login", "/auth/callback", "/auth/logout",
    }
    # path params in api.py's own routes use {..} placeholders; normalize ours the same way for
    # the ones that carry a real id/market so the comparison is apples to apples.
    covered_normalized = {
        p.replace("/999999/", "/{bet_id}/").replace("/match/", "/{market_id}/") for p in covered
    }
    actual = {
        route.path for route in api.app.router.routes
        if getattr(route, "path", None) and route.path not in ("/{full_path:path}",)
        and hasattr(route, "methods")
    }
    missing = actual - covered_normalized
    assert not missing, f"route(s) present in api.py but not classified in this test file: {missing}"
