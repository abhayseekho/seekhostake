"""
tests/test_authz_matrix.py — Systematic authorization coverage: every route in api.py, checked
against all three real session states (no session, bettor session, owner session) over real HTTP
via TestClient. No mocking of the auth layer itself — real signed session cookies, real DB.

Closes a gap flagged explicitly in docs/test-strategy.md: "No test asserting a bettor session
gets 403 on every /api/admin/* route." Ad hoc coverage of specific admin actions already exists
in test_e2e.py; this is the first EXHAUSTIVE, systematic pass over every route at once, so a
route added later without the expected auth call — or one accidentally removed — fails loudly
here instead of silently shipping.

The route inventory below was generated by scanning api.py for which of _require()/_require_owner()
each handler actually calls (not inferred from path naming or copied by hand) — see the repo audit
this file came out of. If a route's auth level changes, this file's inventory must be updated to
match, and that update is itself the record of an intentional decision.
"""
